const jwt = require("jsonwebtoken");
const mongoose = require("mongoose");
const User = require("../models/User");

// Read a Bearer token, cookie token, or x-auth-token header.
const getTokenFromRequest = (req) => {
  const authorization = req.headers?.authorization;

  if (typeof authorization === "string") {
    const match = authorization.match(/^Bearer\s+(.+)$/i);
    if (match && match[1].trim()) {
      return match[1].trim();
    }
  }

  const cookieToken = req.cookies?.token;
  if (typeof cookieToken === "string" && cookieToken.trim()) {
    return cookieToken.trim();
  }

  const headerToken = req.headers?.["x-auth-token"];
  if (typeof headerToken === "string" && headerToken.trim()) {
    return headerToken.trim();
  }

  return null;
};

const sendAccountStatusError = (user, res) => {
  if (user.isDeleted === true) {
    res.status(401).json({
      success: false,
      message: "Your account has been deleted. Please contact the administrator.",
    });
    return true;
  }

  if (user.isActive === false || user.status === "Inactive") {
    res.status(403).json({
      success: false,
      message: "Your account is inactive.",
    });
    return true;
  }

  if (user.status === "Blocked") {
    res.status(403).json({
      success: false,
      message: "Your account has been blocked.",
    });
    return true;
  }

  if (user.status === "Pending") {
    res.status(403).json({
      success: false,
      message: "Your account is pending approval.",
    });
    return true;
  }

  return false;
};

// Verify the JWT and reload account status from MongoDB on each protected request.
const protect = async (req, res, next) => {
  try {
    const token = getTokenFromRequest(req);

    if (!token) {
      return res.status(401).json({
        success: false,
        message: "No token provided. Access denied.",
      });
    }

    const jwtSecret = process.env.JWT_SECRET;
    if (!jwtSecret) {
      console.error("JWT_SECRET is missing from environment variables.");
      return res.status(500).json({
        success: false,
        message: "Server authentication configuration error.",
      });
    }

    let decoded;
    try {
      // Tokens generated by this app use the default HS256 algorithm.
      decoded = jwt.verify(token, jwtSecret, { algorithms: ["HS256"] });
    } catch (error) {
      if (error.name === "TokenExpiredError") {
        return res.status(401).json({
          success: false,
          message: "Token has expired. Please login again.",
        });
      }

      return res.status(401).json({
        success: false,
        message: "Invalid token.",
      });
    }

    const userId = decoded?.id || decoded?._id || decoded?.userId || decoded?.sub;
    if (typeof userId !== "string" || !userId.trim() || !mongoose.isValidObjectId(userId)) {
      return res.status(401).json({
        success: false,
        message: "Invalid token payload.",
      });
    }

    const user = await User.findById(userId)
      .select("_id name email role isDeleted isActive status")
      .lean();

    if (!user) {
      return res.status(401).json({
        success: false,
        message: "User no longer exists. Please login again.",
      });
    }

    if (sendAccountStatusError(user, res)) {
      return;
    }

    req.user = user;
    return next();
  } catch (error) {
    console.error("Authentication middleware error:", error.message);
    return res.status(500).json({
      success: false,
      message: "Server error during authentication.",
    });
  }
};

// Usage: authorize("admin") or authorize("admin", "manager").
const authorize = (...roles) => {
  return (req, res, next) => {
    if (!req.user) {
      return res.status(401).json({
        success: false,
        message: "Authentication required.",
      });
    }

    // Defend against routes accidentally using authorize without protect.
    if (sendAccountStatusError(req.user, res)) {
      return;
    }

    if (!roles.includes(req.user.role)) {
      return res.status(403).json({
        success: false,
        message: `Access denied. Required role: ${roles.join(" or ")}.`,
      });
    }

    return next();
  };
};

module.exports = {
  protect,
  authorize,
};
